"""Pick the wide universe by a rule fixed before any strategy result is seen.

Rule: among currently listed, tradable NASDAQ/NYSE common stocks (no ETFs, ETNs, trusts, funds, ADRs, preferreds,
warrants, or share-class symbols), take those with the highest MEDIAN DOLLAR VOLUME in Q1 2016 (as-traded close x
volume, SIP). Skip the symbols already used in the first universe. Taking the top N by 2015 liquidity avoids
choosing winners with hindsight. It still keeps only survivors (symbols listed today), which flatters results a
little; that is stated in the protocol.

    uv run python scripts/select_universe.py --n 50
"""

from __future__ import annotations

import argparse
import re
from datetime import date

import pandas as pd

from tp import config
from tp.alpaca_data import AlpacaClient

WINDOW = (date(2016, 1, 4), date(2016, 4, 1))  # Alpaca's free history starts in January 2016
MIN_SESSIONS = 55  # of about 61 in the window
BATCH = 100
NOT_COMMON = re.compile(
    r"\b(ETF|ETN|Trust|Fund|Funds|iShares|SPDR|ProShares|Vanguard|Invesco|PowerShares|Direxion|WisdomTree|VanEck|"
    r"Index|Shares|Portfolio|Notes?|Warrants?|Preferred|Depositary|Units?|Rights?|Acquisition|Series|Bond|Income)\b",
    re.I,
)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n", type=int, default=50)
    ap.add_argument("--out", default=str(config.ROOT / "config" / "universe_wide.toml"))
    ap.add_argument("--key", default="wide", help="name of the list inside the output file")
    args = ap.parse_args()

    client = AlpacaClient(config.Settings.from_env())
    existing = set(config.all_symbols())
    assets = [
        a for a in client.assets()
        if a["tradable"] and a["exchange"] in ("NASDAQ", "NYSE") and a["symbol"].isalpha()
        and not NOT_COMMON.search(a["name"]) and a["symbol"] not in existing
    ]
    names = {a["symbol"]: a["name"] for a in assets}
    symbols = sorted(names)
    print(f"{len(symbols)} candidate common stocks after filters")

    rows = []
    for i in range(0, len(symbols), BATCH):
        for sym, bar in client.multi_bars(symbols[i : i + BATCH], "1Day", *WINDOW):
            rows.append((sym, bar["c"] * bar["v"]))
    df = pd.DataFrame(rows, columns=["symbol", "dollar_volume"])
    g = df.groupby("symbol")["dollar_volume"]
    ranked = pd.DataFrame({"sessions": g.size(), "median_dollar_volume": g.median()})
    ranked = ranked[ranked["sessions"] >= MIN_SESSIONS].sort_values("median_dollar_volume", ascending=False)
    top = ranked.head(args.n)

    print(f"{len(ranked)} had at least {MIN_SESSIONS} sessions in Q1 2016. Top {args.n}:")
    for rank, (sym, r) in enumerate(top.iterrows(), 1):
        print(f"{rank:>3} {sym:<6} ${r.median_dollar_volume / 1e6:8.1f}M  {names[sym][:60]}")

    lines = [
        f"# Universe '{args.key}', generated by scripts/select_universe.py. Do not edit by hand.",
        f"# Rule: top {args.n} by median Q1-2016 dollar volume among listed NASDAQ/NYSE common stocks, excluding the first universe.",
        f"# Generated {date.today()} before any strategy was run on these symbols.",
        "[universe]",
        f"{args.key} = [" + ", ".join(f'"{s}"' for s in top.index) + "]",
    ]
    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"\nWrote {args.out}")


if __name__ == "__main__":
    main()
